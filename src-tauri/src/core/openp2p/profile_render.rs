//! Pure OpenP2P → mihomo profile projection.
//!
//! These functions never contain credentials and are the only profile
//! materializer used by the store and by tests.

use std::collections::BTreeMap;

use anyhow::Result;
use serde_yaml_ng::{Mapping, Sequence, Value};

use crate::core::openp2p::schema::{OpenP2PConfig, OpenP2PIssue};

#[path = "profile_render_build.rs"]
mod build;

#[derive(Debug, Default)]
struct ArtifactSet {
    proxies: Vec<Value>,
    proxy_names: Vec<std::string::String>,
    group: Option<Value>,
    rules: Vec<Value>,
    rule_texts: Vec<std::string::String>,
    dns: BTreeMap<std::string::String, Value>,
    warnings: Vec<OpenP2PIssue>,
}

impl ArtifactSet {
    const fn empty() -> Self {
        Self {
            proxies: Vec::new(),
            proxy_names: Vec::new(),
            group: None,
            rules: Vec::new(),
            rule_texts: Vec::new(),
            dns: BTreeMap::new(),
            warnings: Vec::new(),
        }
    }
}

pub(crate) fn render_account_profile_with<T, K>(
    config: &OpenP2PConfig,
    account_id: &str,
    token_ok: T,
    key_ok: K,
) -> Result<Option<std::string::String>>
where
    T: Fn(&str) -> bool,
    K: Fn(&str) -> bool,
{
    if config.account(account_id).is_none() {
        return Ok(None);
    }
    let set = build::build_artifacts_for_account(config, account_id, true, token_ok, key_ok);
    let mut profile = Mapping::new();
    profile.insert(
        Value::from("proxies"),
        Value::Sequence(Sequence::from_iter(set.proxies)),
    );
    let groups = set.group.into_iter().collect::<Vec<_>>();
    profile.insert(
        Value::from("proxy-groups"),
        Value::Sequence(Sequence::from_iter(groups)),
    );
    profile.insert(Value::from("rules"), Value::Sequence(Sequence::from_iter(set.rules)));
    let mut policy = Mapping::new();
    for (domain, servers) in set.dns {
        policy.insert(Value::from(domain.as_str()), servers);
    }
    let mut dns = Mapping::new();
    dns.insert(Value::from("nameserver-policy"), Value::Mapping(policy));
    profile.insert(Value::from("dns"), Value::Mapping(dns));
    let body = serde_yaml_ng::to_string(&Value::Mapping(profile))?;
    Ok(Some(format!(
        "# Generated by Clash Verge OpenP2P for account {account_id}. Edit the account on the OpenP2P page.\n{body}"
    )))
}
