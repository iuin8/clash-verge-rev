//! Source inspection and generated-profile headers for a subscription.

use anyhow::Result;
use serde_yaml_ng::Value;

use crate::core::openp2p::portable::ParsedImport;
use crate::core::openp2p::schema::{self, OpenP2PIssue};
use crate::core::openp2p::secrets::SecretStore;
use crate::core::openp2p::subscriptions::SubscriptionMeta;

pub(crate) struct RenderedProfile {
    /// Ready-to-write YAML, header included.
    pub yaml: std::string::String,
}

pub(crate) fn render_parsed(meta: &SubscriptionMeta, parsed: &ParsedImport) -> Result<RenderedProfile> {
    let header = format!(
        "# Generated by Clash Verge OpenP2P for subscription {} ({}). Edit the imported YAML, not this file.\n",
        meta.name, meta.id
    );
    let body = parsed
        .profile_yaml()
        .ok_or_else(|| anyhow::anyhow!("the imported document has no projected mihomo profile"))?;
    Ok(RenderedProfile {
        yaml: format!("{header}{body}"),
    })
}

pub(crate) fn describe_issues(issues: &[OpenP2PIssue]) -> std::string::String {
    issues
        .iter()
        .map(|issue| format!("{}: {} ({})", issue.path, issue.message, issue.code))
        .collect::<Vec<_>>()
        .join("; ")
}

pub(crate) fn inspect_source(raw: &str, secrets: &SecretStore) -> (Option<u32>, bool, bool) {
    let Ok(value) = serde_yaml_ng::from_str::<Value>(raw) else {
        return (None, false, false);
    };
    let Some(document) = value.as_mapping() else {
        return (None, false, false);
    };
    let contains_mihomo = document.keys().any(|key| key.as_str() != Some(schema::DOCUMENT_KEY));
    let Some(block) = document.get(schema::DOCUMENT_KEY).and_then(Value::as_mapping) else {
        return (None, contains_mihomo, false);
    };
    #[allow(clippy::cast_possible_truncation)]
    let version = block
        .get("version")
        .and_then(Value::as_u64)
        .filter(|version| *version <= u32::MAX as u64)
        .map(|version| version as u32);
    let accounts = block.get("accounts").and_then(Value::as_sequence);
    let self_contained = accounts.is_some_and(|accounts| {
        !accounts.is_empty()
            && accounts.iter().all(|account| {
                let Some(account) = account.as_mapping() else {
                    return false;
                };
                if !account_enabled(account.get("enabled")) {
                    return true;
                }
                let inline = account.get("token").is_some_and(|token| match token {
                    Value::String(token) => !token.trim().is_empty(),
                    Value::Number(_) => true,
                    _ => false,
                });
                let staged = account
                    .get("id")
                    .and_then(Value::as_str)
                    .is_some_and(|id| secrets.token_present(id));
                inline || staged
            })
    });
    (version, contains_mihomo, self_contained)
}

fn account_enabled(value: Option<&Value>) -> bool {
    match value {
        Some(Value::Bool(enabled)) => *enabled,
        Some(Value::Number(number)) => number.as_i64().is_none_or(|enabled| enabled != 0),
        _ => true,
    }
}
